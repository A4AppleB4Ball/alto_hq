"""Render the generated views as markdown. Pure functions, no I/O."""

import os
from pathlib import Path

from scripts.views.items import OWNER_STATUSES, Item

COMMAND = "python -m scripts.views.build"


def header(title: str) -> list[str]:
    return [
        f"# {title}",
        "",
        f"Generated by `{COMMAND}` from the items' frontmatter. Do not edit by hand;",
        "when this view and an item disagree, the item wins.",
        "",
    ]


def link(item: Item, out_file: Path) -> str:
    rel = os.path.relpath(item.path, out_file.parent)
    return f"[{item.id}]({Path(rel).as_posix()})"


def escape(text: str) -> str:
    return " ".join(text.split()).replace("|", "\\|")


def render_by_status(items: list[Item], out_file: Path) -> str:
    lines = header("Items by status")
    statuses = sorted({item.status for item in items})
    for status in statuses:
        group = [item for item in items if item.status == status]
        lines += [f"## {status} ({len(group)})", "", "| Item | Schema | Title |", "|---|---|---|"]
        lines += [f"| {link(i, out_file)} | {i.schema} | {escape(i.title)} |" for i in group]
        lines.append("")
    return "\n".join(lines)


def render_approvals(items: list[Item], out_file: Path) -> str:
    lines = header("Approval queue")
    queue = [item for item in items if item.status in OWNER_STATUSES]
    lines += [f"{len(queue)} items wait on the owner.", ""]
    if queue:
        lines += ["| Item | Status | Title | Waiting on |", "|---|---|---|---|"]
        lines += [
            f"| {link(i, out_file)} | {i.status} | {escape(i.title)} | {escape(i.waiting_on)} |"
            for i in queue
        ]
        lines.append("")
    return "\n".join(lines)
